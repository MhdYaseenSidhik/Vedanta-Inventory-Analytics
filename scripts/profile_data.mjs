// Profiles every file in public/data and prints Markdown. Read-only.
import fs from 'node:fs'
const dir = 'public/data/'
const rd = (n) => JSON.parse(fs.readFileSync(dir + n, 'utf8'))
const man = rd('manifest.json')
const out = []
const p = (s = '') => out.push(s)
const uniq = (rows, k) => [...new Set(rows.map((r) => r[k]))].sort()
const nulls = (rows) => {
  const c = {}
  for (const r of rows) for (const [k, v] of Object.entries(r)) if (v === null) c[k] = (c[k] || 0) + 1
  return c
}
const fields = (rows) => Object.keys(rows[0] || {}).join(', ')
const num = (rows, k) => {
  let mn = Infinity, mx = -Infinity, s = 0
  for (const r of rows) { const v = r[k]; if (typeof v === 'number') { mn = Math.min(mn, v); mx = Math.max(mx, v); s += v } }
  return { min: mn, max: mx, sum: +s.toFixed(3) }
}
p('# Data profile')
p()
p(`Generated by \`scripts/profile_data.mjs\` from \`public/data/\`. schemaVersion ${man.schemaVersion}, asOf ${man.asOf}, generatedAt ${man.generatedAt}.`)
p()
p('## Manifest vs files')
p('| File | manifest rows | rows found | note |')
p('|---|---|---|---|')
const files = {}
for (const f of man.files) {
  const d = rd(f.name)
  files[f.name] = d
  const found = d.rows ? d.rows.length : d.series ? d.series.length : '-'
  p(`| ${f.name} | ${f.rows} | ${found} | ${f.name === 'dims.json' ? 'source rows, not items' : ''} |`)
}
p()
const dims = files['dims.json']
p('## dims.json')
p(`Keys: ${Object.keys(dims).join(', ')}`)
p(`- plants (${dims.plants.length}): ${dims.plants.map((x) => x.plantId).join(', ')}`)
p(`- materialGroups: ${dims.materialGroups.length}; materialTypes: ${dims.materialTypes.map((x) => x.code).join(', ')}; criticality: ${dims.criticality.map((x) => x.code).join(', ')}`)
p(`- movementClasses: ${dims.movementClasses.join(', ')}`)
p(`- inventoryStatuses: ${dims.inventoryStatuses.join(', ')}`)
p()
const k = files['kpis.json']
p('## kpis.json')
p(`Rows ${k.rows.length}; fields: ${fields(k.rows)}; nulls: ${JSON.stringify(nulls(k.rows))}`)
p(`- plantIds: ${uniq(k.rows, 'plantId').join(', ')}; scenarios: ${uniq(k.rows, 'scenario').join(', ')}`)
const months = uniq(k.rows, 'month')
p(`- months: ${months.length} (${months[0]} to ${months.at(-1)})`)
p(`- catalog (${k.catalog.length}):`)
p()
p('| code | label | uom | direction | latest ALL_PLANTS value (baseline) |')
p('|---|---|---|---|---|')
const lastM = months.at(-1)
for (const c of k.catalog) {
  const r = k.rows.find((x) => x.kpiCode === c.code && x.plantId === 'ALL_PLANTS' && x.month === lastM && x.scenario === 'SIMULATED_BASELINE')
  p(`| ${c.code} | ${c.label} | ${c.uom} | ${c.direction} | ${r ? r.value : 'n/a'} |`)
}
const kcodes = new Set(k.rows.map((r) => r.kpiCode))
p()
p(`Codes in rows not in catalog: ${[...kcodes].filter((c) => !k.catalog.find((x) => x.code === c)).join(', ') || 'none'}`)
p(`Rows per scenario: ${JSON.stringify(Object.fromEntries(uniq(k.rows, 'scenario').map((s) => [s, k.rows.filter((r) => r.scenario === s).length])))}`)
p()
for (const n of ['inventory_summary.json', 'materials.json', 'reorder.json', 'plan_vs_actual.json']) {
  const d = files[n]
  p(`## ${n}`)
  p(`Rows ${d.rows.length}; asOf ${d.asOf ?? 'n/a'}; fields: ${fields(d.rows)}`)
  p(`- nulls: ${JSON.stringify(nulls(d.rows))}`)
  p(`- plants: ${uniq(d.rows, 'plantId').join(', ')}; materialTypes: ${uniq(d.rows, 'materialType').join(', ')}`)
  if (d.rows[0].materialGroup !== undefined) p(`- materialGroups: ${uniq(d.rows, 'materialGroup').length}`)
  if (d.rows[0].criticality !== undefined) p(`- criticality: ${uniq(d.rows, 'criticality').join(', ')}`)
  if (d.rows[0].movementClass !== undefined) p(`- movementClass: ${uniq(d.rows, 'movementClass').join(', ')}; inventoryStatus: ${uniq(d.rows, 'inventoryStatus').join(', ')}`)
  if (d.rows[0].abcClass !== undefined) p(`- abcClass: ${uniq(d.rows, 'abcClass').join(', ')}`)
  if (d.rows[0].priority !== undefined) p(`- priority: ${uniq(d.rows, 'priority').join(', ')}; shutdown-linked ${d.rows.filter((r) => r.shutdownId).length}; recommendedPrDate ${uniq(d.rows, 'recommendedPrDate')[0]} to ${uniq(d.rows, 'recommendedPrDate').at(-1)}`)
  if (d.rows[0].month !== undefined) { const m = uniq(d.rows, 'month'); p(`- months: ${m.length} (${m[0]} to ${m.at(-1)})`) }
  if (d.rows[0].materialId !== undefined) p(`- distinct materialId: ${uniq(d.rows, 'materialId').length}`)
  const numeric = Object.keys(d.rows[0]).filter((c) => typeof d.rows[0][c] === 'number' || d.rows.some((r) => typeof r[c] === 'number'))
  p('- numeric ranges:')
  for (const c of numeric) p(`  - ${c}: ${JSON.stringify(num(d.rows, c))}`)
  p()
}
const h = files['forecast_holdout.json']
p('## forecast_holdout.json (backtest)')
p(`kind ${h.kind}; predictionLength ${h.predictionLength}; metric ${JSON.stringify(h.metric)}; error ${JSON.stringify(h.error)}`)
p(`- leaderboard: ${JSON.stringify(h.leaderboard)}`)
p(`- series rows ${h.series.length}; distinct seriesId ${uniq(h.series, 'seriesId').length}; plants ${uniq(h.series, 'plantId').join(', ')}; types ${uniq(h.series, 'materialType').join(', ')}`)
const hm = uniq(h.series, 'month')
p(`- months ${hm.length} (${hm[0]} to ${hm.at(-1)}); nulls ${JSON.stringify(nulls(h.series))}`)
p(`- byPlantMonth ${h.byPlantMonth.length} rows; sum actual ${num(h.byPlantMonth, 'actual').sum}, sum predicted ${num(h.byPlantMonth, 'predicted').sum}`)
p()
const f = files['forecast.json']
p('## forecast.json')
p(`available ${f.available}; reason ${f.reason}; kind ${f.kind}; predictionLength ${f.predictionLength}; ${f.forecastFrom} to ${f.forecastTo}; horizons ${JSON.stringify(f.horizons)}`)
p(`- rows ${f.rows.length}; distinct seriesId ${uniq(f.rows, 'seriesId').length}; plants ${uniq(f.rows, 'plantId').join(', ')}; types ${JSON.stringify(Object.fromEntries(uniq(f.rows, 'materialType').map((t) => [t, f.rows.filter((r) => r.materialType === t).length])))}`)
const fm = uniq(f.rows, 'month')
p(`- months ${fm.length} (${fm[0]} to ${fm.at(-1)}); horizon values ${uniq(f.rows, 'horizon').join(', ')}; nulls ${JSON.stringify(nulls(f.rows))}`)
p(`- predicted ${JSON.stringify(num(f.rows, 'predicted'))}; lower ${JSON.stringify(num(f.rows, 'lower'))}; upper ${JSON.stringify(num(f.rows, 'upper'))}`)
p(`- negative predicted rows ${f.rows.filter((r) => r.predicted < 0).length}; rows with lower>predicted ${f.rows.filter((r) => r.lower > r.predicted).length}; rows with upper<predicted ${f.rows.filter((r) => r.upper < r.predicted).length}`)
p(`- byPlantMonth ${f.byPlantMonth.length} rows (${JSON.stringify(f.byPlantMonth[0])}); sum predicted ${num(f.byPlantMonth, 'predicted').sum}`)
p(`- note: ${f.note}`)
p()
p('## Contract checks')
const checks = []
checks.push(['schemaVersion is 3 (SCHEMA.md)', man.schemaVersion === 3])
checks.push(['every manifest file present and row count matches (excluding dims and forecast files, which count source rows)', man.files.filter((x) => !/dims|forecast/.test(x.name)).every((x) => files[x.name].rows.length === x.rows)])
checks.push(['forecast files rows match manifest', files['forecast.json'].rows.length === 65560 && h.series.length === 65560])
checks.push(['no ALL_PLANTS outside kpis.json', ['inventory_summary.json', 'materials.json', 'reorder.json', 'plan_vs_actual.json'].every((n) => !files[n].rows.some((r) => r.plantId === 'ALL_PLANTS'))])
checks.push(['forecast.available true and horizons [3,6,11]', f.available === true && JSON.stringify(f.horizons) === '[3,6,11]'])
checks.push(['forecast months 2026-01..2026-11', f.forecastFrom === '2026-01' && f.forecastTo === '2026-11' && fm.length === 11])
checks.push(['materialType on every forecast row, only ZSPR/ZSPN', f.rows.every((r) => r.materialType === 'ZSPR' || r.materialType === 'ZSPN')])
for (const [n, ok] of checks) p(`- ${ok ? 'PASS' : 'FAIL'}: ${n}`)
fs.writeFileSync('docs/DATA_PROFILE.md', out.join('\n') + '\n')
console.log(out.join('\n'))
